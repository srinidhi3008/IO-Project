def extract_main_points_t5(email_text: str) -> str:
    """Uses T5 to extract main points from an email."""
    prompt = (
        f"INSTRUCTION: Summarize the key action items and questions from the following email. "
        f"Present them as a bulleted list.\n\n"
        f"EMAIL:\n{email_text}\n\n"
        f"SUMMARY OF POINTS:"
    )

    params = {
        "max_length": 150,
        "min_length": 10,
        "num_beams": 3,
        "early_stopping": True
    }
    return _generate_t5_text(prompt, params)[0]

# --- FIXED: Function for generating variants ---
def generate_reply_variants_t5(email_text: str, tone: str, k_examples: int = 2) -> list:
    """Generates multiple reply variants (3) using beam search."""
    tone_instruction = TONE_INSTRUCTIONS.get(tone.lower(), "Be professional.")

    examples = retrieve_examples(email_text, k=k_examples)
    context = "\n\nHere are some examples of similar replies:\n" + "\n".join(f"- {ex}" for ex in examples) if examples else ""

    prompt = (
        f"INSTRUCTION: Write a {tone} email reply to the following email. {tone_instruction}\n\n"
        f"EMAIL:\n{email_text}\n"
        f"{context}\n\n"
        f"REPLY:"
    )

    params = {
        "max_length": 200,
        "min_length": 15,
        "num_beams": 5,
        "num_return_sequences": 3,
        "early_stopping": True,
        "repetition_penalty": 1.2
    }
    return _generate_t5_text(prompt, params)


