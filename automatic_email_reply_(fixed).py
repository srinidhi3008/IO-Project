# --- CORE AI FUNCTIONS (Your engine) ---

def predict_tone(email_text: str):
    """Predicts tone using the zero-shot classifier."""
    if not email_text.strip(): return {"error": "empty text"}
    if not tone_classifier: return {"tone": "neutral", "confidence": 0.0, "error": "Classifier not loaded"}
    try:
        result = tone_classifier(email_text, TONE_LABELS, multi_label=False)
        tone = result["labels"][0]
        confidence = result["scores"][0]
        print(f"[Tone] Detected: {tone} (Conf: {confidence:.2f})")
        return {"tone": tone, "confidence": float(confidence)}
    except Exception as e:
        print(f"[WARN] HF tone inference failed: {e}")
    return {"tone": "neutral", "confidence": 0.0}

def retrieve_examples(prompt: str, k=3):
    """Retrieves k-most similar replies from the Enron corpus."""
    if TFIDF_MATRIX is None or not CORPUS: return []
    try:
        q_vec = VECTORIZER.transform([prompt])
        sims = cosine_similarity(q_vec, TFIDF_MATRIX)[0]
        idxs = np.argsort(sims)[::-1][:k]
        return [CORPUS[i] for i in idxs]
    except Exception as e:
        print(f"[WARN] TF-IDF retrieval failed: {e}")
        return []

def _generate_t5_text(prompt: str, generation_params: dict) -> list:
    """Internal helper function for T5 generation."""
    if not reply_model:
        return ["Error: Reply model is not loaded."]
    try:
        inputs = tokenizer(prompt, return_tensors="pt", max_length=1024, truncation=True)
        if torch.cuda.is_available():
            inputs = inputs.to("cuda")

        summary_ids = reply_model.generate(
            inputs["input_ids"],
            **generation_params
        )

        replies = tokenizer.batch_decode(summary_ids, skip_special_tokens=True)
        return [reply.strip() for reply in replies]
    except Exception as e:
        print(f"[FATAL] T5 generation failed: {e}")
        return [f"Error: Could not generate reply. {e}"]

# --- FIXED: Function for generating a reply ---
def generate_reply_t5(email_text: str, tone: str = "formal", k_examples: int = 3) -> str:
    """Generates a single, creative reply."""
    tone_instruction = TONE_INSTRUCTIONS.get(tone.lower(), "Be professional.")

    examples = retrieve_examples(email_text, k=k_examples)
    context = "\n\nHere are some examples of similar replies:\n" + "\n".join(f"- {ex}" for ex in examples) if examples else ""

    prompt = (
        f"You are a helpful colleague writing an email. Your goal is to write a natural, conversational reply to the email below.\n\n"
        f"**Your instructions:**\n"
        f"- Your reply must be {tone}. {tone_instruction}\n"
        f"- Start with a friendly greeting (e.g., 'Hi,', or 'Hello,').\n"
        f"- Address all the questions or points from the original email.\n"
        f"- Do not just summarize the action. Write a complete, human-sounding message.\n\n"
        f"**Original Email:**\n{email_text}\n"
        f"{context}\n\n"
        f"**Your Reply:**\n"
    )

    params = {
        "max_length": 250,
        "min_length": 15,
        "do_sample": True,
        "top_p": 0.95,
        "temperature": 0.7,
        "repetition_penalty": 1.1
    }

    return _generate_t5_text(prompt, params)[0]

